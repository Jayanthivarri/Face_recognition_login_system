"""
User Model Module

Defines the User SQLAlchemy ORM model for the face recognition system.
This model represents a registered user with their facial biometric data.

Model Fields:
    - id: Primary key (auto-increment integer)
    - first_name: User's first name (string, required)
    - last_name: User's last name (string, required)
    - email: User's email address (string, unique, required)
    - age: User's age (integer, optional)
    - face_embedding: 128-dimensional face descriptor (JSON)
    - created_at: Account creation timestamp (auto-generated)

Example:
    user = User(
        first_name="John",
        last_name="Doe",
        email="john@example.com",
        age=30,
        face_embedding=[0.1, 0.2, ...]  # 128D array
    )
"""

from sqlalchemy import Column, Integer, String, JSON, DateTime
from sqlalchemy.sql import func
from app.database.base import Base
import json
from typing import List, Optional

class User(Base):
    """
    User database model for face recognition system.
    
    Stores user information and their facial biometric embeddings.
    The face_embedding is a 128-dimensional vector generated by FaceAPI.js.
    """
    
    __tablename__ = "users"
    
    # Primary Key
    id = Column(Integer, primary_key=True, index=True, autoincrement=True)
    
    # User Information
    first_name = Column(String(100), nullable=False, index=True)
    last_name = Column(String(100), nullable=False, index=True)
    email = Column(String(255), unique=True, nullable=False, index=True)
    age = Column(Integer, nullable=True)
    
    # Face Biometric Data
    # Stored as JSON array of 128 floating-point numbers
    # This is a 128-dimensional face descriptor from FaceRecognitionNet
    face_embedding = Column(JSON, nullable=False)
    
    # Metadata
    created_at = Column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
        index=True
    )
    
    def __repr__(self) -> str:
        """String representation of User object."""
        return f"<User(id={self.id}, email='{self.email}', name='{self.first_name} {self.last_name}')>"
    
    def to_dict(self) -> dict:
        """
        Convert User object to dictionary.
        
        Returns:
            dict: User data as dictionary
        """
        return {
            "id": self.id,
            "first_name": self.first_name,
            "last_name": self.last_name,
            "email": self.email,
            "age": self.age,
            "created_at": self.created_at.isoformat() if self.created_at else None
        }

__all__ = ["User"]
